import { AggregateRoot } from '@shared/domain';

import { InvalidWebhookUrlError } from '../errors/notifications-errors';
import { NotificationsEvents } from '../events/notifications-events';

const MAX_URL_LENGTH = 2_000;

// What a center is told about, by webhook. Payloads carry ids and amounts, never personal data.
export const WEBHOOK_EVENTS = [
  'application.submitted',
  'application.decided',
  'contract.signed',
  'disbursement.settled',
  'contract.in_arrears',
  'contract.defaulted',
] as const;
export type WebhookEvent = (typeof WEBHOOK_EVENTS)[number];

export type SubscriptionStatus = 'active' | 'removed';

export interface WebhookSubscriptionProps {
  readonly centerId: string;
  readonly url: string;
  // The HMAC key the center verifies deliveries with; generated by Tramo, shown once.
  readonly secret: string;
  readonly status: SubscriptionStatus;
  readonly createdAt: Date;
  readonly changedAt: Date;
}

// An http(s) URL without credentials. Whether its host may be private is the delivery's call
// (it depends on the environment), not the URL's.
export function parseWebhookUrl(raw: string): string {
  const value = raw.trim();
  if (value.length === 0 || value.length > MAX_URL_LENGTH) {
    throw new InvalidWebhookUrlError(`expected 1 to ${String(MAX_URL_LENGTH)} characters`);
  }
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new InvalidWebhookUrlError('not an absolute URL');
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') {
    throw new InvalidWebhookUrlError('only http and https are delivered to');
  }
  if (url.username || url.password) {
    throw new InvalidWebhookUrlError('credentials do not belong in the URL');
  }
  if (url.hash) {
    throw new InvalidWebhookUrlError('a fragment is never sent');
  }
  return url.toString();
}

// The endpoint of a training center that receives its events. One per center: configuring it
// again replaces the URL and the secret.
export class WebhookSubscription extends AggregateRoot {
  private constructor(
    id: string,
    private props: WebhookSubscriptionProps,
  ) {
    super(id);
  }

  static subscribe(input: {
    id: string;
    centerId: string;
    url: string;
    secret: string;
    now: Date;
  }): WebhookSubscription {
    const subscription = new WebhookSubscription(input.id, {
      centerId: input.centerId,
      url: parseWebhookUrl(input.url),
      secret: input.secret,
      status: 'active',
      createdAt: input.now,
      changedAt: input.now,
    });
    subscription.recordSubscribed(input.now);
    return subscription;
  }

  static reconstitute(id: string, props: WebhookSubscriptionProps): WebhookSubscription {
    return new WebhookSubscription(id, props);
  }

  get centerId(): string {
    return this.props.centerId;
  }

  get url(): string {
    return this.props.url;
  }

  get secret(): string {
    return this.props.secret;
  }

  get status(): SubscriptionStatus {
    return this.props.status;
  }

  get createdAt(): Date {
    return this.props.createdAt;
  }

  get changedAt(): Date {
    return this.props.changedAt;
  }

  get active(): boolean {
    return this.props.status === 'active';
  }

  // A new URL and secret, or the same URL with a new secret (a rotation); a removed subscription
  // comes back.
  reconfigure(url: string, secret: string, now: Date): void {
    this.props = {
      ...this.props,
      url: parseWebhookUrl(url),
      secret,
      status: 'active',
      changedAt: now,
    };
    this.recordSubscribed(now);
  }

  // Idempotent. Deliveries already made stay listed; pending ones are no longer posted.
  remove(now: Date): void {
    if (this.props.status === 'removed') {
      return;
    }
    this.props = { ...this.props, status: 'removed', changedAt: now };
    this.record({
      eventType: NotificationsEvents.WebhookUnsubscribed,
      aggregateType: 'WebhookSubscription',
      aggregateId: this.id,
      occurredAt: now,
      payload: { subscriptionId: this.id, centerId: this.props.centerId },
    });
  }

  private recordSubscribed(now: Date): void {
    this.record({
      eventType: NotificationsEvents.WebhookSubscribed,
      aggregateType: 'WebhookSubscription',
      aggregateId: this.id,
      occurredAt: now,
      payload: { subscriptionId: this.id, centerId: this.props.centerId },
    });
  }
}
